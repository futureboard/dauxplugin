//! Versioned plug-in state serialization and migration for DAUxPlug.
//!
//! A plug-in's state is the one thing a user cannot afford to lose. This crate is the
//! deterministic, self-describing binary container the SDK saves it in, plus the migration
//! machinery that keeps ten-year-old projects loadable.
//!
//! It has **no dependencies** (the `serde` feature is optional and off by default) and
//! contains no `unsafe`.
//!
//! # The container
//!
//! A blob is a 20-byte header — magic `DAUXST\0\0`, container format version, plug-in
//! schema version, entry count — followed by length-prefixed `(key, type tag, value)`
//! entries in insertion order, all little-endian. Values are `f64`, `i64`, `bool`, `str`,
//! `bytes`, or a nested group delimited by begin/end markers. [`mod@format`] documents
//! the layout byte for byte.
//!
//! Encoding is **deterministic**: the same sequence of `put_*` calls always yields exactly
//! the same bytes, so state hashes are stable and a diff of two saved projects is
//! meaningful. Nothing about the machine, the moment or hash-map iteration order can leak
//! in.
//!
//! ```
//! use daux_state::{StateReader, StateVersion, StateWriter};
//!
//! let mut w = StateWriter::new(StateVersion(1));
//! w.put_f64("gain", -6.0);
//! w.begin_group("filter");
//! w.put_str("mode", "lowpass");
//! w.put_f64("cutoff", 1_000.0);
//! w.end_group();
//! let bytes = w.try_finish()?;
//!
//! let r = StateReader::from_bytes(&bytes)?;
//! assert_eq!(r.f64("gain")?, -6.0);
//! assert_eq!(r.str("filter/mode")?, "lowpass");        // '/' walks into groups
//! assert_eq!(r.group("filter")?.f64("cutoff")?, 1_000.0);
//! assert_eq!(r.opt_f64("filter/resonance"), None);     // never written, never invented
//! # Ok::<(), daux_state::StateError>(())
//! ```
//!
//! # Parsing is hostile-input handling
//!
//! Project files travel: they are e-mailed, downloaded, generated by scripts and edited by
//! other tools. Everything a host hands a plug-in is therefore untrusted, and the parser
//! treats it that way.
//!
//! * A blob larger than [`StateLimits::max_blob_bytes`] (64 MiB by default) is rejected
//!   before it is looked at, and [`StateReader::read_from`] stops pulling from a stream
//!   at that bound so an endless pipe cannot exhaust memory.
//! * Every length prefix is checked against the configured maximum **and** against the
//!   bytes actually remaining in the input, so nothing is ever allocated on the strength
//!   of a number the attacker chose. Total allocation is bounded by the input size.
//! * Keys are bounded ([`StateLimits::max_key_bytes`], 4 KiB), entry counts are bounded,
//!   and group nesting is bounded ([`StateLimits::max_depth`], 64) — which also bounds the
//!   recursive drop of the resulting tree.
//! * Unknown type tags, non-`0`/`1` boolean bytes, invalid UTF-8, unbalanced groups,
//!   trailing bytes and entry-count mismatches are all errors.
//! * Nothing in this crate panics on malformed input, and there is no `unsafe`.
//!
//! # Versioning and migration
//!
//! [`StateVersion`] is the plug-in's *schema* version, independent of the container
//! format. abi-v1 §12 requires a plug-in to load every schema version it has ever shipped,
//! or fail cleanly with no side effects. [`MigrationChain`] does that with one small
//! `from → from + 1` [`StateDoc`] rewrite per version bump:
//!
//! ```
//! use daux_state::{MigrationChain, StateDoc, StateVersion};
//!
//! let chain = MigrationChain::new(StateVersion(3))
//!     .step(StateVersion(1), |doc| doc.rename("gain_db", "gain"))
//!     .step(StateVersion(2), |doc| { doc.insert("bypass", false)?; Ok(()) });
//!
//! let mut old = StateDoc::new(StateVersion(1));
//! old.insert("gain_db", -6.0)?;
//!
//! let now = chain.migrate(old)?;
//! assert_eq!(now.version(), StateVersion(3));
//! assert_eq!(now.f64("gain")?, -6.0);
//! # Ok::<(), daux_state::StateError>(())
//! ```
//!
//! Migration is all-or-nothing: a failing step aborts and the partially rewritten document
//! is dropped, so a host never observes a half-applied load.
//!
//! # Threading
//!
//! Everything here is `[main-thread]`. Saving and loading allocate, and abi-v1 §11.3 only
//! ever calls `daux.state/1` on the main thread; nothing in this crate may be called from
//! `process`.

